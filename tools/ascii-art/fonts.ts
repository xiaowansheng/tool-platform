export const FONTS: Record<string, AsciiFont> = {
  slant: SLANT_FONT,
  doom: DOOM_FONT,
  bubble: BUBBLE_FONT
};

export function renderAscii(text: string, fontKey: string): string {
  const font = FONTS[fontKey] ?? SLANT_FONT;
  const result: string[] = Array(font.height).fill("");

  for (let i = 0; i < text.length; i++) {
    const char = text[i].toUpperCase();
    const charRows = font.chars[char] ?? font.chars[" "];
    
    for (let r = 0; r < font.height; r++) {
      result[r] += charRows[r];
    }
  }

  return result.join("\n");
}
